def build_taxonomy_files():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    csv_path = os.path.join(base_dir, "crop_health_taxonomy.csv")
    json_path = os.path.join(base_dir, "crop_health_taxonomy.json")

    # CSV headers as strictly requested by user
    csv_headers = [
        "Crop",
        "Disease_or_Pest",
        "Scientific_Name",
        "Symptoms",
        "Affected_Plant_Part",
        "Visual_Detectability",
        "Required_Dataset",
        "Dataset_Availability",
        "Detection_Method",
        "Diagnostic_Limitations",
        "Reference_Source"
    ]

    print(f"Compiling {len(TAXONOMY_DATA)} crop health conditions...")

    # Write CSV
    with open(csv_path, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=csv_headers, extrasaction="ignore")
        writer.writeheader()
        for item in TAXONOMY_DATA:
            writer.writerow(item)
    print(f"-> Generated CSV: {csv_path} ({os.path.getsize(csv_path)} bytes)")

    # Write JSON
    with open(json_path, mode="w", encoding="utf-8") as f:
        json.dump(TAXONOMY_DATA, f, indent=2, ensure_ascii=False)
    print(f"-> Generated JSON: {json_path} ({os.path.getsize(json_path)} bytes)")

if __name__ == "__main__":
    build_taxonomy_files()
